@pytest.mark.asyncio
async def test_structure_prefixes_stay_in_same_document_permissions_and_recheck_current_role(knowledge_context, monkeypatch):
    c = knowledge_context
    for filename, code, role in [("employee.md", "EMP-101", "employee"), ("support.md", "SUP-202", "support"), ("admin.md", "ADM-303", "admin")]:
        await publish(c, filename, f"# Operations\n\n## {code}\n\nInspect the matching device.", role)
    retriever = await build_retriever(c.factory, c.qdrant, c.settings)
    employee = await retriever.retrieve("ADM-303", user_access_level="employee")
    assert {hit.citation.source_path for hit in employee} <= {"employee.md"}
    support = await retriever.retrieve("SUP-202", user_access_level="support")
    assert support[0].citation.source_path == "support.md"
    admin = await retriever.retrieve("ADM-303", user_access_level="admin")
    assert admin[0].citation.source_path == "admin.md"
    original_query = c.qdrant.query_points
    async def tighten_access(**kwargs):
        result = await original_query(**kwargs)
        async with c.factory.begin() as session:
            source = await session.scalar(select(KnowledgeSource).where(KnowledgeSource.source_path == "employee.md"))
            source.access_level = "admin"
        return result
    monkeypatch.setattr(c.qdrant, "query_points", tighten_access)
    assert await retriever.retrieve("EMP-101", user_access_level="employee") == []


@pytest.mark.asyncio
async def test_legacy_compatibility_does_not_accept_tampered_manifest_or_another_model(knowledge_context):
    c = knowledge_context
    old = await legacy(c)
    assert (await build_retriever(c.factory, c.qdrant, c.settings, old.revision_id)).revision.id == old.revision_id
    async with c.factory.begin() as session:
        revision = await session.get(KnowledgeRevision, old.revision_id)
        revision.pipeline_config = {**v1_config(), "minimum_evidence_score": 0.01}
    with pytest.raises(ValueError, match="differs"):
        await build_retriever(c.factory, c.qdrant, c.settings, old.revision_id)
    async with c.factory.begin() as session:
        revision = await session.get(KnowledgeRevision, old.revision_id)
        revision.pipeline_config = v1_config()
        revision.embedding_model = "unapproved-model"
    with pytest.raises(HTTPException) as denied:
        await c.service.activate_revision(c.owner, old.revision_id)
    assert denied.value.status_code == 409


@pytest.mark.asyncio
async def test_token_budget_failure_happens_before_qdrant_or_active_pointer_side_effect(knowledge_context, monkeypatch):
    import app.production.knowledge as module
    import app.rag.ingest as ingestion
    c = knowledge_context
    old = await legacy(c)
    _, _, initial = await publish(c, "reviewed.md", "# Reviewed\n\nA previously reviewed procedure.")
    job = await c.service.enqueue_upload(c.owner, "new.md", "New", "employee", b"# New\n\nAnother procedure.")
    await c.service.process_job(job["id"])
    await c.service.job_detail(job["id"])
    vector_creates = []
    original_create = c.qdrant.create_collection
    async def tracked_create(**kwargs):
        vector_creates.append(kwargs["collection_name"])
        return await original_create(**kwargs)
    class BudgetFailure(DeterministicEmbedder):
        async def token_counts(self, texts):
            error_type = getattr(ingestion, "EmbeddingInputTooLong", ValueError)
            raise error_type("完整输入超过512 token上限，请人工整理。")
    monkeypatch.setattr(module, "build_embedder", lambda settings: BudgetFailure(dimensions=32))
    monkeypatch.setattr(c.qdrant, "create_collection", tracked_create)
    task = await c.service.enqueue_publish(c.owner, job["id"])
    await c.service.process_next_job()
    detail = await c.service.index_job_detail(task["id"])
    assert detail["status"] == "failed" and detail["error"] == "embedding_input_too_long"
    assert vector_creates == []
    assert await c.service.active_revision_id() == initial["revision_id"]
    assert (await c.qdrant.count(collection_name=old.collection, exact=True)).count == 1
    async with c.factory() as session:
        assert await session.scalar(select(KnowledgeSource).where(KnowledgeSource.source_path == "new.md")) is None
