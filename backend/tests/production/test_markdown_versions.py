@pytest.mark.asyncio
async def test_same_bytes_can_be_prepared_reviewed_and_published_without_rewriting_old_snapshot(knowledge_context, tmp_path):
    c = knowledge_context
    old = await legacy(c)
    corpus = tmp_path / "corpus"
    corpus.mkdir()
    (corpus / "old.md").write_bytes(old.content.encode())
    spec = importlib.util.spec_from_file_location("markdown_upgrade_import", Path(__file__).resolve().parents[3] / "scripts/ingest_knowledge.py")
    cli = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(cli)
    args = cli.build_parser().parse_args(["--directory", str(corpus), "--actor-id", c.owner, "--dry-run"])
    assert (await cli.prepare_production(args, c.settings, c.factory, c.service))[0]["status"] == "would_enqueue"
    args.dry_run = False
    prepared = await cli.prepare_production(args, c.settings, c.factory, c.service)
    assert prepared[0]["status"] == "queued"
    await c.service.process_job(prepared[0]["job_id"])
    await c.service.job_detail(prepared[0]["job_id"])
    result = await c.service.execute_publish(c.owner, prepared[0]["job_id"])
    assert result["revision_id"] != old.revision_id
    assert (await cli.prepare_production(args, c.settings, c.factory, c.service))[0]["status"] == "unchanged"
    async with c.factory() as session:
        snapshot = await session.scalar(select(KnowledgeSnapshot).where(KnowledgeSnapshot.revision_id == old.revision_id))
        source = await session.get(KnowledgeSource, old.document_id)
    assert snapshot.content == old.content and snapshot.parser_version is None
    assert source.content_hash == old.digest and source.parser_version == PARSER
    assert (await build_retriever(c.factory, c.qdrant, c.settings, old.revision_id)).revision.pipeline_config == v1_config()


@pytest.mark.asyncio
async def test_pre_upgrade_ready_job_cannot_publish_without_new_parse_and_preview(knowledge_context):
    c = knowledge_context
    job_id = str(uuid4())
    async with c.factory.begin() as session:
        session.add(KnowledgeJob(id=job_id, user_id=c.owner, title="Old", source_path="unused.md", original_filename="old.md",
            content_hash="0" * 64, access_level="employee", status="ready", content="# Old\n\nOld procedure.",
            sections=[{"heading": "Old", "content": "Old procedure."}], previewed_at=now()))
    detail = await c.service.job_detail(job_id)
    assert detail["requires_reparse"] is True
    with pytest.raises(HTTPException) as denied:
        await c.service.enqueue_publish(c.owner, job_id)
    assert denied.value.status_code == 409
    with pytest.raises(HTTPException) as direct:
        await c.service.execute_publish(c.owner, job_id)
    assert direct.value.status_code == 409 and await c.service.active_revision_id() is None


