PARSER = "markdown-it-py-4.2.0-structure-v1"


def v1_config():
    # Frozen manifest copied from the pre-change source, not generated by v2.
    return {"version": 1, "max_chars": 800, "overlap_chars": 120, "tokenizer": "cjk-bigram-latin-v1",
        "pdf_extraction": "ruled-cells-normalized-page-context-v2", "pdf_chunking": "atomic-row-page-v1", "max_table_chars": 800,
        "legacy_pdf_policy": "exclude-unlocated-sources-v1", "normalize_embeddings": True, "query_instruction": "",
        "distance": "Cosine", "reranker": "lexical-v1", "vector_weight": 0.65, "bm25_weight": 0.35,
        "minimum_evidence_score": 0.35}


async def publish(c, filename, text, access="employee", title="Generic guide"):
    job = await c.service.enqueue_upload(c.owner, filename, title, access, text.encode())
    await c.service.process_job(job["id"])
    preview = await c.service.job_detail(job["id"])
    assert preview["status"] == "ready", preview["error"]
    result = await c.service.execute_publish(c.owner, job["id"])
    return job, preview, result


async def legacy(c):
    content = "# Legacy\n\n## Old steps\n\nLegacy procedure: inspect the cable.\n"
    raw = "Legacy procedure: inspect the cable."
    document_id, revision_id, chunk_id = str(uuid4()), str(uuid4()), str(uuid4())
    collection = revision_collection(c.settings.qdrant_collection, revision_id)
    vector = (await DeterministicEmbedder(dimensions=32).encode(["Legacy\n" + raw]))[0]
    await c.qdrant.create_collection(collection_name=collection,
        vectors_config=models.VectorParams(size=32, distance=models.Distance.COSINE))
    await c.qdrant.upsert(collection_name=collection, wait=True, points=[models.PointStruct(id=chunk_id, vector=vector,
        payload={"document_id": document_id, "access_level": "employee", "revision_id": revision_id})])
    digest = hashlib.sha256(content.encode()).hexdigest()
    async with c.factory.begin() as session:
        session.add(KnowledgeSource(id=document_id, title="Legacy", source_path="old.md", content_hash=digest,
            content=content, access_level="employee", status="active", version=1))
        session.add(KnowledgeRevision(id=revision_id, collection_name=collection, status="ready", document_count=1,
            chunk_count=1, embedding_model="deterministic:32", embedding_revision="sha256-token-v1", dimensions=32,
            pipeline_config=v1_config(), created_by=c.owner))
        await session.flush()
        session.add(KnowledgeSnapshot(revision_id=revision_id, document_id=document_id, title="Legacy", source_path="old.md",
            content=content, content_hash=digest, access_level="employee"))
        start = content.index(raw)
        session.add(RevisionChunk(id=chunk_id, revision_id=revision_id, document_id=document_id, chunk_index=0,
            content=raw, source_title="Legacy", source_path="old.md", char_start=start, char_end=start + len(raw), access_level="employee"))
        session.add(KnowledgeActivePointer(id=1, revision_id=revision_id))
    return SimpleNamespace(document_id=document_id, revision_id=revision_id, chunk_id=chunk_id,
        content=content, raw=raw, digest=digest, collection=collection)


@pytest.mark.asyncio
async def test_reviewed_markdown_structure_is_persisted_and_used_for_actual_index_inputs(knowledge_context, monkeypatch):
    import app.production.knowledge as module
    c = knowledge_context
    encoded = []
    class CapturingEmbedder(DeterministicEmbedder):
        async def encode(self, texts):
            encoded.extend(texts)
            return await super().encode(texts)
    embedder = CapturingEmbedder(dimensions=32)
    monkeypatch.setattr(module, "build_embedder", lambda settings: embedder)
    text = "# Guide\n\n## RoomBox B200 E-42\n\n```sh\n# literal comment\n\necho inspect\n```\n"
    job, preview, result = await publish(c, "new.md", text)
    assert preview["sections"][0]["section_path"] == ["Guide", "RoomBox B200 E-42"]
    async with c.factory() as session:
        revision = await session.get(KnowledgeRevision, result["revision_id"])
        rows = list(await session.scalars(select(RevisionChunk).where(RevisionChunk.revision_id == revision.id)))
        source = await session.scalar(select(KnowledgeSource).where(KnowledgeSource.source_path == "new.md"))
        snapshot = await session.scalar(select(KnowledgeSnapshot).where(KnowledgeSnapshot.revision_id == revision.id))
    assert revision.pipeline_config["version"] == 2
    assert revision.pipeline_config["markdown_parser"] == PARSER
    assert source.parser_version == snapshot.parser_version == PARSER
    assert len(rows) == 1 and rows[0].structure["section_path"] == ["Guide", "RoomBox B200 E-42"]
    assert text[rows[0].char_start:rows[0].char_end] == rows[0].content
    assert encoded == ["Generic guide\n章节：Guide > RoomBox B200 E-42\n" + rows[0].content]
    points, _ = await c.qdrant.scroll(collection_name=revision.collection_name, limit=10, with_payload=True)
    assert points[0].payload["structure"] == rows[0].structure
    assert (await c.service.job_detail(job["id"]))["status"] == "published"


@pytest.mark.asyncio
async def test_unknown_old_markdown_is_not_relabelled_or_automatically_added_to_new_pipeline(knowledge_context):
    c = knowledge_context
    old = await legacy(c)
    _, _, result = await publish(c, "new.md", "# New\n\nCurrent procedure.")
    assert result["excluded_documents"] == ["old.md"]
    async with c.factory() as session:
        source = await session.get(KnowledgeSource, old.document_id)
        old_chunk = await session.get(RevisionChunk, old.chunk_id)
        old_revision = await session.get(KnowledgeRevision, old.revision_id)
        paths = list(await session.scalars(select(KnowledgeSnapshot.source_path).where(KnowledgeSnapshot.revision_id == result["revision_id"])))
    assert paths == ["new.md"]
    assert source.content == old.content and source.content_hash == old.digest and source.parser_version is None
    assert old_chunk.content == old.raw and old_chunk.structure is None and old_revision.pipeline_config == v1_config()
    assert (await c.qdrant.count(collection_name=old.collection, exact=True)).count == 1
    request = SimpleNamespace(app=SimpleNamespace(state=SimpleNamespace(knowledge_service=c.service)))
    listing = await documents(request, principal=Principal(c.owner, "Admin", "admin"))
    row = next(row for row in listing["documents"] if row["id"] == old.document_id)
    assert row["requires_reparse"] is True and row["reparse_reason"] == "markdown_structure"
    historical = await build_retriever(c.factory, c.qdrant, c.settings, old.revision_id)
    assert (await historical.retrieve("Legacy procedure", user_access_level="employee"))[0].citation.index_revision == old.revision_id
    assert (await c.service.activate_revision(c.owner, old.revision_id))["revision_id"] == old.revision_id


